"""
Step 1 — Data quality checks on the ingested KKBox tables.

Each check counts the affected rows and records the handling decision that
Step 2+ applies. Nothing is modified here; the decisions are documented so
the metrics can be traced back to them.

Output: output/data_quality_notes.md
"""



from config import OUTPUT, PARQUET_DIR, connect, parquet

con = connect("01")
T, M = f"'{parquet('transactions')}'", f"'{parquet('members')}'"


def one(sql):
    return con.execute(sql).fetchone()


n_tx, n_tx_users = one(f"SELECT count(*), count(DISTINCT msno) FROM {T}")
n_mem = one(f"SELECT count(*) FROM {M}")[0]

# (table, issue, affected rows, denominator, decision)
checks = []


def check(table, issue, where, decision, src=T, denom=None):
    n = one(f"SELECT count(*) FROM {src} WHERE {where}")[0]
    checks.append((table, issue, n, denom or (n_tx if src == T else n_mem), decision))


check("transactions", "`payment_plan_days = 0`", "payment_plan_days = 0",
      "Plan length taken from `membership_expire_date - transaction_date` instead.")
check("transactions", "`plan_list_price = 0` but paid > 0", "plan_list_price = 0 AND actual_amount_paid > 0",
      "List price ignored; revenue always uses `actual_amount_paid`.")
check("transactions", "`actual_amount_paid = 0` (free trial / promo)", "actual_amount_paid = 0 AND NOT is_cancel",
      "Membership counts as active but contributes 0 MRR (status `free`).")
check("transactions", "Paid below list price (discount)",
      "actual_amount_paid > 0 AND plan_list_price > 0 AND actual_amount_paid < plan_list_price",
      "Kept; discount flag used as a churn feature in Step 4.")
check("transactions", "`is_cancel = 1` (user cancelled)", "is_cancel",
      "Not revenue. Its `membership_expire_date` becomes the user's new end date.")
check("transactions", "Expiry before transaction date (non-cancel)",
      "membership_expire_date < transaction_date AND NOT is_cancel",
      "Dropped: no coverage period can be built from it.")
check("transactions", "Expiry before 2015 or after 2018",
      "membership_expire_date < DATE '2015-01-01' OR membership_expire_date > DATE '2018-12-31'",
      "Dropped: data-entry errors (1970 epoch, years up to 2036).")
check("transactions", "User missing from `members`",
      f"msno NOT IN (SELECT msno FROM {M})",
      "Kept for revenue metrics; segment = `unknown` for member attributes.")
check("members", "Age `bd` <= 0", "bd <= 0",
      "Age treated as unknown.", src=M)
check("members", "Age `bd` > 100", "bd > 100",
      "Age treated as unknown.", src=M)
check("members", "`gender` missing", "gender IS NULL",
      "Kept as its own `unknown` category.", src=M)

tx_start, tx_end = one(f"SELECT min(transaction_date), max(transaction_date) FROM {T}")
plan_mix = con.execute(f"""
    SELECT payment_plan_days AS days, count(*) AS n
    FROM {T} WHERE NOT is_cancel GROUP BY 1 ORDER BY n DESC LIMIT 6""").fetchall()
labels = {
    name: one(f"SELECT count(*), avg(is_churn::INT) FROM '{parquet(name)}'")
    for name in ("train_v1", "train_v2")
}

logs_note = "_`user_logs.parquet` not ingested yet — re-run this step after `00_ingest.py user_logs`._"
if (PARQUET_DIR / "user_logs.parquet").exists():
    L = f"'{parquet('user_logs')}'"
    n_logs, neg, huge = one(f"""
        SELECT count(*), count(*) FILTER (WHERE total_secs < 0),
               count(*) FILTER (WHERE total_secs > 86400) FROM {L}""")
    logs_note = (
        f"{n_logs:,} rows. `total_secs < 0`: {neg:,}; `total_secs` > 24h in one day: {huge:,}. "
        "Both are overflow artefacts in the source — `total_secs` is clipped to [0, 86400]."
    )


def pct(n, d):
    return f"{n / d:.1%}"


lines = [
    "# Data quality notes — KKBox",
    "",
    "Generated by `scripts/01_data_quality.py`. Every number below is recomputed on each run.",
    "",
    "## Coverage",
    "",
    f"- Transactions: {n_tx:,} rows (v1 + v2, exact duplicates removed), {n_tx_users:,} users, "
    f"{tx_start} → {tx_end}.",
    f"- Members: {n_mem:,} rows.",
    f"- Churn labels: train_v1 {labels['train_v1'][0]:,} users ({labels['train_v1'][1]:.1%} churn, "
    f"Feb 2017 expiries); train_v2 {labels['train_v2'][0]:,} users ({labels['train_v2'][1]:.1%} churn, "
    "Mar 2017 expiries).",
    f"- User logs: {logs_note}",
    "- **Left-censoring:** no transactions before Jan 2015, so members on long plans bought earlier are "
    "invisible until they renew. Metrics are reported from **Jul 2015** onward (6-month warm-up).",
    "",
    "Most common plan lengths (non-cancel transactions): "
    + ", ".join(f"{d} days ({pct(n, n_tx)})" for d, n in plan_mix) + ".",
    "",
    "## Issues and handling",
    "",
    "| Table | Issue | Rows | Share | Handling |",
    "|---|---|---:|---:|---|",
]
lines += [f"| {t} | {i} | {n:,} | {pct(n, d)} | {dec} |" for t, i, n, d, dec in checks]
lines += [
    "",
    "## Churn definition",
    "",
    "Kaggle's label: a user is churned if there is **no new valid subscription within 30 days after "
    "the current membership expires**. The monthly snapshot (Step 2) uses the same rule, so the "
    "metric churn rate and the model labels agree.",
    "",
]

OUTPUT.mkdir(exist_ok=True)
(OUTPUT / "data_quality_notes.md").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
